"""Genuine C2PA Content Credentials via the official CAI Python bindings (`c2pa-python`).

Signing embeds a C2PA manifest store into the asset (JPEG, PNG, WebP, MP4, MOV).
Verification parses the manifest with the SDK and maps the SDK's validation codes to
VERIFRAME statuses, keeping *signature/binding validity* and *signer trust* separate.
"""
from __future__ import annotations

import io
import json
import threading
from datetime import datetime, timezone

import c2pa

from app.core.config import settings
from app.services.provenance.keys import load_keys

C2PA_SIGN_MIMES = {"image/jpeg", "image/png", "image/webp", "video/mp4", "video/quicktime"}

# Validation codes that only concern trust in the signing credential (not tampering).
TRUST_ONLY_FAILURES = {"signingCredential.untrusted"}

_lock = threading.Lock()


def sdk_info() -> dict:
    from importlib.metadata import version

    return {"python_package": f"c2pa-python {version('c2pa-python')}", "native_sdk": c2pa.sdk_version()}


def available() -> bool:
    try:
        c2pa.sdk_version()
        return True
    except Exception:  # pragma: no cover
        return False


def _trust_anchors_pem() -> str:
    km = load_keys()
    pem = km.root_cert_pem.decode()
    extra = settings.extra_trust_anchors
    if extra and extra.exists():
        pem += "\n" + extra.read_text()
    return pem


def _context(with_trust: bool) -> c2pa.Context:
    cfg: dict = {"verify": {"verify_trust": True}}
    if with_trust:
        cfg["trust"] = {"trust_anchors": _trust_anchors_pem()}
    return c2pa.Context(c2pa.Settings.from_dict(cfg))


def sign(data: bytes, mime: str, title: str, *, workflow: str, software_agent: str, description: str,
         extra: dict | None = None) -> tuple[bytes, dict]:
    """Embed a signed C2PA manifest. Returns (signed_bytes, manifest_definition).

    workflow:
      * "capture" -> Builder intent CREATE with IPTC digitalSourceType `digitalCapture`
                     (c2pa.created action generated by the SDK). Used only for browser captures.
      * "upload"  -> Builder intent EDIT: the SDK records the received bytes as the parentOf
                     ingredient and adds a c2pa.opened action linked to it. No claim is made about
                     how the content was originally created.
    A vendor assertion `org.veriframe.signing-context` records the truthful signing context.
    """
    if mime not in C2PA_SIGN_MIMES:
        raise ValueError(f"C2PA embedding is not supported for {mime} by this SDK build")
    km = load_keys()
    context_assertion = {
        "service": "VERIFRAME demo signing service",
        "workflow": workflow,
        "software_agent": software_agent,
        "signed_at": datetime.now(timezone.utc).isoformat(),
        "statement": description,
        "hardware_attestation": False,
        "signer_trust": "local demo CA - not on the C2PA trust list",
        **(extra or {}),
    }
    manifest = {
        "claim_generator_info": [{"name": "VERIFRAME", "version": settings.app_version}],
        "title": title,
        "format": mime,
        "assertions": [{"label": "org.veriframe.signing-context", "data": context_assertion}],
    }
    info = c2pa.C2paSignerInfo(c2pa.C2paSigningAlg.ES256, km.signer_chain_pem, km.signer_key_pem, None)
    out = io.BytesIO()
    with _lock:
        signer = c2pa.Signer.from_info(info)
        try:
            builder = c2pa.Builder(manifest)
            if workflow == "capture":
                builder.set_intent(c2pa.C2paBuilderIntent.CREATE, c2pa.C2paDigitalSourceType.DIGITAL_CAPTURE)
            else:
                builder.set_intent(c2pa.C2paBuilderIntent.EDIT)
            builder.sign(signer, mime, io.BytesIO(data), out)
        finally:
            signer.close()
    manifest["intent"] = "CREATE/digitalCapture" if workflow == "capture" else "EDIT (parentOf ingredient = received bytes)"
    return out.getvalue(), manifest


def _read(data: bytes, mime: str, with_trust: bool, manifest_data: bytes | None):
    with _lock:
        ctx = _context(with_trust)
        try:
            reader = c2pa.Reader(mime, io.BytesIO(data), manifest_data, context=ctx)
        except c2pa.C2paError.ManifestNotFound:
            return None
        try:
            return {
                "state": reader.get_validation_state(),
                "results": reader.get_validation_results() or {},
                "store": json.loads(reader.json()),
                "embedded": reader.is_embedded(),
            }
        finally:
            reader.close()


def verify(data: bytes, mime: str, manifest_data: bytes | None = None) -> dict:
    """Return a structured C2PA verification result.

    status is one of VALID_PROVENANCE, VALID_BUT_UNTRUSTED_SIGNER, TAMPERED_OR_INVALID,
    NO_PROVENANCE_FOUND, UNSUPPORTED_OR_UNREADABLE.
    """
    base = {"implementation": "C2PA Content Credentials (c2pa-python)", "sdk": sdk_info()}
    try:
        r = _read(data, mime, True, manifest_data)
    except c2pa.C2paError as e:
        msg = str(e).split("\n")[0][:240]
        name = type(e).__name__.lstrip("_")
        broken = any(k in name for k in ("Manifest", "Verify", "Signature", "Assertion", "Json"))
        return {**base, "status": "TAMPERED_OR_INVALID" if broken else "UNSUPPORTED_OR_UNREADABLE",
                "manifest_found": broken, "error": f"{name}: {msg}", "steps": [
                    {"key": "discovery", "label": "Manifest parsing", "state": "fail",
                     "detail": ("A provenance structure was present but could not be parsed/validated: " if broken else "The file could not be assessed: ") + msg}]}
    except Exception as e:  # pragma: no cover - defensive
        return {**base, "status": "UNSUPPORTED_OR_UNREADABLE", "manifest_found": False, "error": str(e)[:240], "steps": []}
    if r is None:
        return {**base, "status": "NO_PROVENANCE_FOUND", "manifest_found": False, "steps": [
            {"key": "discovery", "label": "Manifest discovery", "state": "absent",
             "detail": "No C2PA manifest (JUMBF) found in the file" + (" or the supplied sidecar" if manifest_data else "") + "."}]}

    active = (r["results"].get("activeManifest") or {})
    failures = active.get("failure", []) or []
    successes = active.get("success", []) or []
    codes_fail = {f.get("code") for f in failures}
    codes_ok = {s.get("code") for s in successes}
    hard_failures = [f for f in failures if f.get("code") not in TRUST_ONLY_FAILURES]

    binding_ok = not any(c and (c.startswith("assertion.dataHash") or c.startswith("assertion.bmffHash")
                               or c.startswith("assertion.boxesHash") or c.startswith("assertion.hashedURI")) for c in codes_fail)
    binding_checked = any(c and ("dataHash" in c or "bmffHash" in c or "boxesHash" in c) for c in codes_ok | codes_fail)
    sig_ok = "claimSignature.validated" in codes_ok and not any(c and c.startswith("claimSignature") for c in codes_fail)
    trusted = "signingCredential.trusted" in codes_ok and not codes_fail & TRUST_ONLY_FAILURES

    if hard_failures:
        status = "TAMPERED_OR_INVALID"
    elif trusted:
        status = "VALID_PROVENANCE"
    else:
        status = "VALID_BUT_UNTRUSTED_SIGNER"

    store = r["store"]
    m = store.get("manifests", {}).get(store.get("active_manifest") or "", {})
    sig = m.get("signature_info", {}) or {}
    actions = []
    for a in m.get("assertions", []) or []:
        if a.get("label", "").startswith("c2pa.actions"):
            for act in (a.get("data") or {}).get("actions", []):
                actions.append({k: act.get(k) for k in ("action", "digitalSourceType", "softwareAgent", "when", "description") if act.get(k) is not None})
    assertion_labels = [a.get("label") for a in m.get("assertions", []) or []]
    signing_context = next((a.get("data") for a in m.get("assertions", []) or [] if a.get("label") == "org.veriframe.signing-context"), None)
    ingredients = [{"title": i.get("title"), "relationship": i.get("relationship"), "format": i.get("format")} for i in m.get("ingredients", []) or []]

    steps = [
        {"key": "discovery", "label": "Manifest discovery", "state": "pass",
         "detail": f"C2PA manifest store found ({'embedded in file' if r['embedded'] else 'supplied sidecar'}); active manifest {store.get('active_manifest')}"},
        {"key": "binding", "label": "Content binding (hard-binding hash)", "state": "pass" if binding_ok and binding_checked else ("fail" if not binding_ok else "unknown"),
         "detail": "Hash of the uploaded bytes matches the hash recorded in the signed claim." if binding_ok and binding_checked
         else "; ".join(f["explanation"] for f in failures if "Hash" in (f.get("code") or "") or "hash" in (f.get("explanation") or "")) or "Binding could not be confirmed."},
        {"key": "signature", "label": "Claim signature (COSE, " + str(sig.get("alg", "?")) + ")", "state": "pass" if sig_ok else "fail",
         "detail": "Signature over the claim verifies with the certificate in the manifest." if sig_ok
         else "; ".join(f["explanation"] for f in failures if (f.get("code") or "").startswith("claimSignature")) or "Signature not validated."},
        {"key": "trust", "label": "Signer certificate trust", "state": "pass" if trusted else "warn",
         "detail": ("Certificate chains to an anchor in this verifier's LOCAL DEMO trust policy (not the public C2PA trust list)."
                    if trusted else "Certificate does not chain to any anchor in the current trust policy. Mathematical validity is reported separately.")},
    ]
    return {
        **base,
        "status": status,
        "manifest_found": True,
        "validation_state": r["state"],
        "signature_valid": sig_ok,
        "binding_valid": binding_ok and binding_checked,
        "signer_trusted": trusted,
        "trust_policy": "VERIFRAME local demo trust policy (demo root CA" + (" + extra anchors" if settings.extra_trust_anchors else "") + ")",
        "signer": {"common_name": sig.get("common_name"), "issuer": sig.get("issuer"), "alg": sig.get("alg"),
                   "cert_serial_number": sig.get("cert_serial_number"), "time": sig.get("time")},
        "claim_generator": m.get("claim_generator_info"),
        "title": m.get("title"),
        "actions": actions,
        "assertions": assertion_labels,
        "signing_context": signing_context,
        "ingredients": ingredients,
        "active_manifest": store.get("active_manifest"),
        "timestamp": sig.get("time"),
        "timestamp_note": None if sig.get("time") else "No RFC 3161 trusted timestamp (offline demo signer); the 'when' field in assertions is signer-asserted.",
        "validation_codes": {"success": sorted(c for c in codes_ok if c), "failure": [{"code": f.get("code"), "explanation": f.get("explanation")} for f in failures],
                             "informational": [i.get("code") for i in active.get("informational", []) or []]},
        "steps": steps,
    }
